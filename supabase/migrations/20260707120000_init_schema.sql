-- 6. POLICIES
-- ============================================================================

-- ---------------------------------------------------------------- accounts
-- No INSERT policy: account creation happens only via the create-account
-- Edge Function (service role), which also provisions the matching
-- auth.users row (and synthetic email, if applicable). No DELETE policy:
-- deletion is a soft delete via UPDATE is_active = false.

create policy accounts_select on public.accounts
  for select to authenticated
  using (
    id = public.current_account_id()
    or public.is_master_admin()
    or created_by = public.current_account_id()
  );

create policy accounts_update_managed on public.accounts
  for update to authenticated
  using (
    public.is_master_admin()
    or created_by = public.current_account_id()
  )
  with check (
    public.is_master_admin()
    or created_by = public.current_account_id()
  );

-- ---------------------------------------------------------------- sessions
-- Everyone can see session status; only admin/master_admin can open/close,
-- set winning_number, share_method, or adjust total_data_set_limit.

create policy sessions_select_all on public.sessions
  for select to authenticated
  using (true);

create policy sessions_insert_admin on public.sessions
  for insert to authenticated
  with check (public.is_admin_or_above());

create policy sessions_update_admin on public.sessions
  for update to authenticated
  using (public.is_admin_or_above())
  with check (public.is_admin_or_above());

-- ------------------------------------------------------------ entry_limits
-- Users can read their own limits; admin/master_admin can read/write limits
-- for the users they manage. No policy allows a user to write their own.

create policy entry_limits_select on public.entry_limits
  for select to authenticated
  using (
    user_id = public.current_account_id()
    or public.managed_by_current_admin(user_id)
  );

create policy entry_limits_insert_admin on public.entry_limits
  for insert to authenticated
  with check (public.managed_by_current_admin(user_id));

create policy entry_limits_update_admin on public.entry_limits
  for update to authenticated
  using (public.managed_by_current_admin(user_id))
  with check (public.managed_by_current_admin(user_id));

create policy entry_limits_delete_admin on public.entry_limits
  for delete to authenticated
  using (public.managed_by_current_admin(user_id));

-- ----------------------------------------------- limit_table_profiles (+ rows)
create policy limit_table_profiles_all on public.limit_table_profiles
  for all to authenticated
  using (created_by = public.current_account_id() or public.is_master_admin())
  with check (created_by = public.current_account_id() or public.is_master_admin());

create policy limit_table_profile_rows_all on public.limit_table_profile_rows
  for all to authenticated
  using (
    exists (
      select 1 from public.limit_table_profiles p
      where p.id = profile_id
        and (p.created_by = public.current_account_id() or public.is_master_admin())
    )
  )
  with check (
    exists (
      select 1 from public.limit_table_profiles p
      where p.id = profile_id
        and (p.created_by = public.current_account_id() or public.is_master_admin())
    )
  );

-- ------------------------------------------------------------- bet_entries
-- SELECT: a user sees their own entries; admin/master_admin sees entries
-- from users they manage. Partners have NO access to raw bet_entries.
-- INSERT: only the user themselves, only while the session is open, and
-- only within their remaining limit for that number (defense-in-depth —
-- the validate-bet-entry Edge Function is the authoritative, race-safe check).
-- NO UPDATE/DELETE policy exists for anyone — entries are immutable.

create policy bet_entries_select on public.bet_entries
  for select to authenticated
  using (
    user_id = public.current_account_id()
    or public.managed_by_current_admin(user_id)
  );

create policy bet_entries_insert_own on public.bet_entries
  for insert to authenticated
  with check (
    user_id = public.current_account_id()
    and amount > 0
    and exists (
      select 1 from public.sessions s
      where s.id = bet_entries.session_id
        and s.status = 'open'
    )
    and (
      coalesce(
        (select el.limit_value from public.entry_limits el
         where el.session_id = bet_entries.session_id
           and el.user_id = bet_entries.user_id
           and el.number = bet_entries.number),
        0
      )
      >=
      amount + coalesce(
        (select sum(be.amount) from public.bet_entries be
         where be.session_id = bet_entries.session_id
           and be.user_id = bet_entries.user_id
           and be.number = bet_entries.number),
        0
      )
    )
  );

-- --------------------------------------------------------- share_history
-- Written only via the distribute-over-limit Edge Function (service role).
-- No client INSERT/UPDATE/DELETE policy. Readable by admin/master_admin.

create policy share_history_select_admin on public.share_history
  for select to authenticated
  using (public.is_admin_or_above());

-- ----------------------------------------------------- over_limit_records
create policy over_limit_records_select_admin on public.over_limit_records
  for select to authenticated
  using (public.is_admin_or_above());

-- --------------------------------------------------------- partner_shares
-- Partners see only their own share rows; admin/master_admin see all.

create policy partner_shares_select on public.partner_shares
  for select to authenticated
  using (
    partner_id = public.current_account_id()
    or public.is_admin_or_above()
  );

-- ------------------------------------------------------ warning_messages
create policy warning_messages_insert_admin on public.warning_messages
  for insert to authenticated
  with check (public.is_admin_or_above());

create policy warning_messages_select on public.warning_messages
  for select to authenticated
  using (
    public.is_admin_or_above()
    or (
      -- compare as text, not by casting current_role() into audience_role_type:
      -- current_role() can be 'admin'/'master_admin', which is not a valid
      -- audience_role_type value and would raise an error on cast instead of
      -- just evaluating false.
      audience_role::text = public.current_role()::text
      and (
        audience_scope = 'all'
        or exists (
          select 1 from public.session_targets st
          where st.warning_message_id = warning_messages.id
            and st.account_id = public.current_account_id()
        )
      )
    )
  );

-- -------------------------------------------------------- session_targets
create policy session_targets_insert_admin on public.session_targets
  for insert to authenticated
  with check (public.is_admin_or_above());

create policy session_targets_select on public.session_targets
  for select to authenticated
  using (
    account_id = public.current_account_id()
    or public.is_admin_or_above()
  );


