-- --------------------------------------------------------------------------
-- accounts — all Master Admin / Admin / User / Partner records
-- --------------------------------------------------------------------------
create table public.accounts (
  id                     uuid primary key default gen_random_uuid(),
  auth_user_id           uuid unique references auth.users (id) on delete cascade,
  role                   public.account_role not null,
  username               text not null,
  email                  text,                          -- populated only for master_admin
  email_verified_at      timestamptz,                    -- populated only for master_admin
  commission_rate        numeric(5,2) not null default 0 check (commission_rate >= 0 and commission_rate <= 100),
  payout_rate            integer not null default 0 check (payout_rate >= 0),
  data_share_percentage  numeric(5,2) check (data_share_percentage is null or (data_share_percentage >= 0 and data_share_percentage <= 100)),
  created_by             uuid references public.accounts (id),
  is_active              boolean not null default true,
  created_at             timestamptz not null default now(),
  updated_at             timestamptz not null default now(),

  -- only partners carry a data_share_percentage
  constraint accounts_share_pct_only_for_partner
    check (role = 'partner' or data_share_percentage is null),

  -- master_admin must have an email; everyone else must not need one to log in
  constraint accounts_master_admin_email
    check (role <> 'master_admin' or email is not null)
);

create unique index accounts_username_unique_idx on public.accounts (lower(username));
create index accounts_created_by_idx on public.accounts (created_by);
create index accounts_role_idx on public.accounts (role);

