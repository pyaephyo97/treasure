-- ASSUMPTIONS BAKED INTO THIS MIGRATION (confirm before running in prod):
--
-- 1. AUTH STRATEGY (not yet explicitly confirmed with product owner):
--    Supabase Auth (auth.users) is used for ALL roles, including username-only
--    ones. Since auth.users requires an email, non-master-admin accounts get a
--    synthetic email of the form  "<username>@users.treasure.internal"
--    generated by the create-account Edge Function. The UI only ever asks for
--    a username; the Edge Function looks up/derives the synthetic email server
--    side. Master Admin uses a real email with Supabase's normal email
--    verification flow. Passwords are managed entirely by Supabase Auth
--    (bcrypt under the hood) — there is no password column in public.accounts.
--
-- 2. Resolved open questions from spec §10 (2026-07-07):
--    - Sessions are archived & browsable (append-only sessions table).
--    - bet_entries are immutable once inserted — no UPDATE/DELETE policy for
--      ANY role, including admin.
--    - No cap on users/partners per admin.
--    - Equal-split rounding remainder stays with Admin (already in spec §4.4;
--      enforced in the distribute-over-limit Edge Function, not in SQL).
--    - No partner-of-partner (sub-partner) hierarchy for Phase 1.
--
-- 3. All INSERT/UPDATE/DELETE on accounts, and all writes on the audit-style
--    tables (over_limit_records, share_history, partner_shares), happen via
--    Edge Functions using the service role key, which bypasses RLS entirely.
--    Intentionally NO client-facing INSERT policy exists for those tables —
--    absence of a policy = default deny under RLS.
--
-- 4. The live "Total Data" / "Over Limit" views (spec §5.2.5, computed from
--    bet_entries + an admin-adjustable set_limit) are NOT stored tables —
--    compute them with a query/view at read time. over_limit_records only
--    stores a frozen snapshot at the moment of a "Share to Partners" action,
--    tied to a share_history entry (see §7 below).
--
