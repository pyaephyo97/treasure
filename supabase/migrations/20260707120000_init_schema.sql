-- ============================================================================
-- 4. RLS HELPER FUNCTIONS
-- (security definer so they can read public.accounts regardless of the
-- caller's own RLS visibility — standard Supabase pattern)
-- ============================================================================

create function public.current_account_id()
returns uuid
language sql stable security definer set search_path = public
as $$
  select id from public.accounts where auth_user_id = auth.uid();
$$;

create function public.current_role()
returns public.account_role
language sql stable security definer set search_path = public
as $$
  select role from public.accounts where auth_user_id = auth.uid();
$$;

create function public.is_master_admin()
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.accounts
    where auth_user_id = auth.uid() and role = 'master_admin'
  );
$$;

create function public.is_admin_or_above()
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.accounts
    where auth_user_id = auth.uid() and role in ('admin', 'master_admin')
  );
$$;

-- true if target_account_id was created by the current admin, or the caller is master_admin
create function public.managed_by_current_admin(target_account_id uuid)
returns boolean
language sql stable security definer set search_path = public
as $$
  select
    public.is_master_admin()
    or exists (
      select 1 from public.accounts a
      where a.id = target_account_id
        and a.created_by = public.current_account_id()
    );
$$;


